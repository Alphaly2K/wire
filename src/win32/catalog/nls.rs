const T32: ArchitecturePlan = ArchitecturePlan {
    dlls: &["kernel32.dll"],
    execution: ExecutionPolicy::Typed,
};
const L32: ArchitecturePlan = ArchitecturePlan {
    dlls: &["kernel32.dll"],
    execution: ExecutionPolicy::LegacyUnimplemented,
};
const T64: ArchitecturePlan = ArchitecturePlan {
    dlls: &["kernel32.dll", "kernelbase.dll"],
    execution: ExecutionPolicy::Typed,
};
const A64: ArchitecturePlan = ArchitecturePlan {
    dlls: &[],
    execution: ExecutionPolicy::Absent,
};
const A32: ArchitecturePlan = ArchitecturePlan {
    dlls: &[],
    execution: ExecutionPolicy::Absent,
};
const fn declaration(
    id: NlsApi,
    name: &'static str,
    parameters: &'static [Parameter],
    returns: ReturnConvention,
    x86: ArchitecturePlan,
    x64: ArchitecturePlan,
) -> Contract {
    Contract::new(ApiId::Nls(id), name, parameters, returns,
        "CP932 virtual defaults; limited Unicode/NLS vocabulary; architecture-specific flags, bounds, error and partial-output rules; locale enumeration uses a dedicated process callback adapter",
        [x86, x64])
}
