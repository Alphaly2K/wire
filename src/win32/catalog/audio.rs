const fn declaration(
    id: AudioApi,
    name: &'static str,
    parameters: &'static [Parameter],
) -> Contract {
    Contract::new(ApiId::Audio(id), name, parameters, ReturnConvention::Uint32,
        "Historical PE32 declaration; current Wasm adapters support both ABIs. MCI returns 274; wave reports no devices and open returns 6, clearing non-NULL output only outside WAVE_FORMAT_QUERY. No wave backend; LastError is preserved.",
        [ArchitecturePlan { dlls: &["winmm.dll"], execution: ExecutionPolicy::Typed },
         ArchitecturePlan { dlls: &[], execution: ExecutionPolicy::Absent }])
}
const fn wave(id: AudioApi, name: &'static str, parameters: &'static [Parameter]) -> Contract {
    Contract::new(ApiId::Audio(id), name, parameters, ReturnConvention::Uint32,
        "No wave input/output devices: enumeration is zero, open fails with 6 without callbacks, capabilities fail with 2, operations on nonexistent handles fail with 5. Output capability size zero and error-text size zero are successful no-ops. English MM/WAVE error descriptions support terminated truncation; LastError is preserved.",
        [ArchitecturePlan { dlls: &["winmm.dll"], execution: ExecutionPolicy::LegacyUnimplemented }; 2])
}
